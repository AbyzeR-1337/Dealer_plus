// Writes js/data/photos.js: which generated item photos exist (assets/photos/<variant>/<file>.jpg).
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
const out = {};
for (const v of ['clean', 'worn', 'broken']) {
  const d = `assets/photos/${v}`;
  out[v] = existsSync(d) ? readdirSync(d).filter((f) => f.endsWith('.jpg') && !f.includes('.tmp')).map((f) => f.slice(0, -4)).sort() : [];
}
writeFileSync('js/data/photos.js', `// generated by scripts/photo_manifest.mjs — item photos that exist, by variant\nexport const PHOTO_FILES = ${JSON.stringify(out)};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.length}`).join(', '));
