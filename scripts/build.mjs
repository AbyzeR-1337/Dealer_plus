// Builds the static site into ./dist for GitHub Pages.
// - copies the app files
// - writes js/config.js from env (SUPABASE_URL / SUPABASE_ANON_KEY) when present
// - stamps a build id into sw.js / index.html for cache busting
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const out = 'dist';
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const p of ['index.html', 'manifest.webmanifest', 'sw.js', '.nojekyll', 'css', 'js', 'icons']) {
  if (existsSync(p)) cpSync(p, `${out}/${p}`, { recursive: true });
}

let build = process.env.GITHUB_SHA ? process.env.GITHUB_SHA.slice(0, 8) : '';
if (!build) { try { build = execSync('git rev-parse --short HEAD').toString().trim(); } catch { build = String(Date.now()); } }
build += '-' + Date.now().toString(36);

const url = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (process.env.SUPABASE_ANON_KEY || '').trim();
writeFileSync(`${out}/js/config.js`,
  `// generated by scripts/build.mjs\nwindow.GR_CONFIG = ${JSON.stringify({ supabaseUrl: url, supabaseKey: key, build })};\n`);

for (const f of ['sw.js', 'index.html']) {
  const p = `${out}/${f}`;
  writeFileSync(p, readFileSync(p, 'utf8').replaceAll('__BUILD__', build));
}
console.log(`built ${out}/ (build ${build}, online: ${url ? 'yes' : 'no'})`);
