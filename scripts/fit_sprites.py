#!/usr/bin/env python3
"""Writes js/data/sprite_fit.js: the tight bounding box of every cut-out sprite (1x sheet pixels),
so items are framed by the object itself rather than by the hand-drawn rectangle.
Run after scripts/cut_sprites.py."""
import os, re, json
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K = 2
rows = re.findall(r"\['(\w+)', (\d), (\d+), (\d+), (\d+), (\d+)", open(os.path.join(ROOT, 'js', 'data', 'sprites.js')).read())
alpha = {}
fit = {}
for sid, sh, x0, y0, x1, y1 in rows:
    sh = int(sh); x0, y0, x1, y1 = map(int, (x0, y0, x1, y1))
    if sh not in alpha:
        alpha[sh] = np.asarray(Image.open(os.path.join(ROOT, 'assets', 'sheets', f'sheet{sh}.webp')).convert('RGBA'))[:, :, 3]
    a = alpha[sh][y0 * K:y1 * K, x0 * K:x1 * K] > 40
    ys, xs = np.nonzero(a)
    if len(xs) < 20:
        continue
    bx0, bx1 = np.percentile(xs, [0.3, 99.7]); by0, by1 = np.percentile(ys, [0.3, 99.7])
    fit[sid] = [round(x0 + bx0 / K - 1, 1), round(y0 + by0 / K - 1, 1), round((bx1 - bx0) / K + 2, 1), round((by1 - by0) / K + 2, 1)]
with open(os.path.join(ROOT, 'js', 'data', 'sprite_fit.js'), 'w') as f:
    f.write('// generated by scripts/fit_sprites.py: tight [x, y, w, h] of each cut-out sprite in 1x sheet pixels\n')
    f.write('export const FIT = ' + json.dumps(fit, separators=(',', ':')) + ';\n')
print(len(fit), 'sprites fitted')
